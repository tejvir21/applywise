import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { cleanup, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { MaterialsEditor } from '@/components/MaterialsEditor'
import {
  generateAnswer,
  generateCoverLetter,
  markMaterialsReviewed,
} from '@/services/applications'

afterEach(() => {
  cleanup()
  vi.unstubAllGlobals()
})

function stubFetch(payload: unknown, status = 200) {
  vi.stubGlobal(
    'fetch',
    vi.fn().mockResolvedValue({
      status,
      json: async () => payload,
    }),
  )
}

const MATERIALS = {
  materials: {
    coverLetter: 'Existing draft body',
    answers: [{ question: 'Why us?', answer: 'Because.', verified: false, sensitive: false }],
  },
  provenance: { provider: 'mock', model: 'mock-template-v1', generatedAt: '2026-01-01T00:00:00.000Z' },
  status: 'DRAFT',
}

function renderEditor() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  return render(
    <QueryClientProvider client={client}>
      <MaterialsEditor applicationId="app-1" editable reviewable onChanged={() => {}} />
    </QueryClientProvider>,
  )
}

describe('materials services', () => {
  it('parses generation responses', async () => {
    stubFetch({ success: true, data: { coverLetter: 'Body', flaggedGaps: ['gap'], provider: 'mock', model: 'm' } })
    await expect(generateCoverLetter('app-1')).resolves.toMatchObject({ coverLetter: 'Body' })

    stubFetch({ success: true, data: { answer: { question: 'Q', answer: 'A', verified: false, sensitive: false } } })
    await expect(generateAnswer('app-1', 'Q')).resolves.toMatchObject({ answer: { verified: false } })

    stubFetch({ success: true, data: MATERIALS })
    await expect(markMaterialsReviewed('app-1')).resolves.toMatchObject({ status: 'DRAFT' })
  })
})

describe('MaterialsEditor', () => {
  it('renders drafts with provenance and unreviewed badge', async () => {
    stubFetch({ success: true, data: MATERIALS })
    renderEditor()

    expect(await screen.findByDisplayValue('Existing draft body')).toBeInTheDocument()
    expect(screen.getByText(/Generated by mock/)).toBeInTheDocument()
    expect(screen.getByText('AI draft — unreviewed')).toBeInTheDocument()
    expect(screen.getByText('Why us?')).toBeInTheDocument()
  })

  it('generates a cover letter and shows flagged gaps', async () => {
    const user = userEvent.setup()
    stubFetch({ success: true, data: { materials: { answers: [] }, status: 'DRAFT' } })
    renderEditor()
    await screen.findByText('No tailored resume draft yet.')

    stubFetch({
      success: true,
      data: { coverLetter: 'Fresh body', flaggedGaps: ['No verified record of required skill: rust'], provider: 'mock', model: 'm' },
    })
    await user.click(screen.getByRole('button', { name: 'Generate' }))

    expect(await screen.findByDisplayValue('Fresh body')).toBeInTheDocument()
    expect(screen.getByText('No verified record of required skill: rust')).toBeInTheDocument()
  })

  it('surfaces the replace requirement instead of overwriting edits', async () => {
    const user = userEvent.setup()
    stubFetch({ success: true, data: MATERIALS })
    renderEditor()
    await screen.findByDisplayValue('Existing draft body')

    stubFetch(
      { success: false, error: { code: 'CONFLICT', message: 'Draft exists', details: {} } },
      409,
    )
    await user.click(screen.getByRole('button', { name: 'Regenerate' }))

    expect(await screen.findByRole('alert')).toHaveTextContent('Draft exists')
    // The user's text is preserved.
    expect(screen.getByDisplayValue('Existing draft body')).toBeInTheDocument()
  })

  it('saves edited answers with verification flags', async () => {
    const user = userEvent.setup()
    stubFetch({ success: true, data: MATERIALS })
    renderEditor()
    await screen.findByText('Why us?')

    await user.click(screen.getByRole('checkbox', { name: /Verified by me/ }))
    stubFetch({ success: true, data: MATERIALS })
    await user.click(screen.getByRole('button', { name: 'Save answers' }))

    await waitFor(() => {
      expect(vi.mocked(fetch)).toHaveBeenCalledWith(
        expect.stringContaining('/api/applications/app-1/materials'),
        expect.objectContaining({
          method: 'PATCH',
          body: expect.stringContaining('"verified":true'),
        }),
      )
    })
    expect(await screen.findByText('Answers saved.')).toBeInTheDocument()
  })

  it('marks materials reviewed and shows the reviewed badge', async () => {
    const user = userEvent.setup()
    stubFetch({ success: true, data: MATERIALS })
    renderEditor()
    await screen.findByText('Why us?')

    stubFetch({ success: true, data: { ...MATERIALS, reviewedAt: '2026-02-02T00:00:00.000Z' } })
    await user.click(screen.getByRole('button', { name: 'Mark materials as reviewed' }))

    expect(await screen.findByText('Materials marked as reviewed.')).toBeInTheDocument()
  })

  it('previews the tailored resume draft with skills and gaps', async () => {
    stubFetch({
      success: true,
      data: {
        materials: {
          answers: [],
          tailoredResume: {
            summary: 'Ada — Engineer. Draft only.',
            highlights: ['5 year(s) of professional experience'],
            skillsUsed: ['TypeScript'],
            flaggedGaps: ['No verified record of required skill: rust'],
            generatedAt: '2026-01-01T00:00:00.000Z',
          },
        },
        status: 'DRAFT',
      },
    })
    renderEditor()

    expect(await screen.findByText('Ada — Engineer. Draft only.')).toBeInTheDocument()
    expect(screen.getByText(/Verified skills used: TypeScript/)).toBeInTheDocument()
    expect(screen.getByText('No verified record of required skill: rust')).toBeInTheDocument()
    expect(screen.getByText('The original resume file is unchanged.')).toBeInTheDocument()
  })
})
