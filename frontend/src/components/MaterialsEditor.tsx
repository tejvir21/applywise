import { useState } from 'react'
import { useQueryClient } from '@tanstack/react-query'
import { useApplicationMaterials } from '@/hooks/useApplications'
import {
  generateAnswer,
  generateCoverLetter,
  generateResumeDraft,
  markMaterialsReviewed,
  updateApplicationMaterials,
} from '@/services/applications'

type AnswerEdit = { question: string; answer: string; verified: boolean; sensitive: boolean }

export function MaterialsEditor({
  applicationId,
  editable,
  reviewable,
  onChanged,
}: {
  applicationId: string
  editable: boolean
  reviewable: boolean
  onChanged: () => void
}) {
  const queryClient = useQueryClient()
  const materialsQuery = useApplicationMaterials(applicationId)
  const [coverText, setCoverText] = useState('')
  const [coverGaps, setCoverGaps] = useState<string[]>([])
  const [question, setQuestion] = useState('')
  const [answers, setAnswers] = useState<AnswerEdit[]>([])
  const [replace, setReplace] = useState(false)
  const [busy, setBusy] = useState<string | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [notice, setNotice] = useState<string | null>(null)

  const data = materialsQuery.data
  // Sync server drafts into local form state when fresh data arrives (the
  // documented render-time pattern for "adjust state when props change").
  // Local edits are preserved while the server snapshot is unchanged.
  const serverSnapshot = data
    ? `${applicationId}|${data.materials.coverLetter ?? ''}|${JSON.stringify(data.materials.answers)}`
    : null
  const [syncedSnapshot, setSyncedSnapshot] = useState<string | null>(null)
  if (serverSnapshot && serverSnapshot !== syncedSnapshot && data) {
    setSyncedSnapshot(serverSnapshot)
    setCoverText(data.materials.coverLetter ?? '')
    setAnswers(data.materials.answers.map((a) => ({ ...a })))
  }

  async function refresh() {
    await queryClient.invalidateQueries({ queryKey: ['application-materials', applicationId] })
    onChanged()
  }

  async function run(label: string, fn: () => Promise<void>) {
    setError(null)
    setNotice(null)
    setBusy(label)
    try {
      await fn()
      await refresh()
    } catch (err) {
      setError(err instanceof Error ? err.message : `${label} failed`)
    } finally {
      setBusy(null)
    }
  }

  if (materialsQuery.isPending) return <p className="text-sm text-slate-600">Loading materials…</p>
  if (materialsQuery.isError || !data) {
    return (
      <div role="alert" className="rounded-md border border-red-300 bg-red-50 px-3 py-2 text-sm text-red-800">
        Could not load materials.
        <button type="button" onClick={() => materialsQuery.refetch()} className="ml-2 underline">
          Retry
        </button>
      </div>
    )
  }

  return (
    <div className="mt-4 rounded-xl border border-slate-200 bg-white px-4 py-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h2 className="text-sm font-semibold text-slate-900">Application materials</h2>
        {data.reviewedAt ? (
          <span className="inline-flex items-center rounded-full bg-emerald-100 px-2.5 py-0.5 text-xs font-semibold text-emerald-800">
            reviewed
          </span>
        ) : (
          <span className="inline-flex items-center rounded-full bg-amber-100 px-2.5 py-0.5 text-xs font-semibold text-amber-800">
            AI draft — unreviewed
          </span>
        )}
      </div>
      {data.provenance?.provider && (
        <p className="mt-1 text-xs text-slate-500">
          Generated by {data.provenance.provider}
          {data.provenance.model ? ` (${data.provenance.model})` : ''}
          {data.provenance.generatedAt ? ` on ${new Date(data.provenance.generatedAt).toLocaleString()}` : ''} from
          verified profile, resume, and job data.
        </p>
      )}

      {error && (
        <p role="alert" className="mt-2 rounded-md border border-red-300 bg-red-50 px-3 py-2 text-sm text-red-800">
          {error}
        </p>
      )}
      {notice && (
        <p role="status" className="mt-2 rounded-md border border-emerald-300 bg-emerald-50 px-3 py-2 text-sm text-emerald-800">
          {notice}
        </p>
      )}

      <div className="mt-3">
        <h3 className="text-sm font-semibold text-slate-900">Cover letter (draft)</h3>
        <textarea
          aria-label="Cover letter draft"
          value={coverText}
          onChange={(e) => setCoverText(e.target.value)}
          disabled={!editable}
          rows={6}
          className="mt-1 block w-full rounded-md border border-slate-300 px-2 py-1.5 text-sm disabled:bg-slate-100"
        />
        {coverGaps.length > 0 && (
          <div className="mt-2 rounded-md border border-amber-300 bg-amber-50 px-3 py-2 text-sm text-amber-800">
            <p className="font-semibold">Missing information</p>
            <ul className="list-disc pl-5">
              {coverGaps.map((gap) => (
                <li key={gap}>{gap}</li>
              ))}
            </ul>
          </div>
        )}
        {editable && (
          <div className="mt-2 flex flex-wrap items-center gap-2">
            <button
              type="button"
              disabled={busy !== null}
              onClick={() =>
                void run('cover-letter generation', async () => {
                  const res = await generateCoverLetter(applicationId, replace)
                  setCoverText(res.coverLetter)
                  setCoverGaps(res.flaggedGaps)
                  setNotice('Cover letter draft generated. Review every line before use.')
                })
              }
              className="rounded-md bg-slate-900 px-3 py-1.5 text-sm font-medium text-white disabled:opacity-50"
            >
              {busy === 'cover-letter generation' ? 'Generating…' : data.materials.coverLetter ? 'Regenerate' : 'Generate'}
            </button>
            <button
              type="button"
              disabled={busy !== null}
              onClick={() =>
                void run('cover-letter save', async () => {
                  await updateApplicationMaterials(applicationId, { coverLetter: coverText })
                  setNotice('Cover letter saved.')
                })
              }
              className="rounded-md border border-slate-300 px-3 py-1.5 text-sm font-medium text-slate-700 disabled:opacity-50"
            >
              Save
            </button>
            <label className="text-xs text-slate-600">
              <input
                type="checkbox"
                checked={replace}
                onChange={(e) => setReplace(e.target.checked)}
                className="mr-1"
              />
              Replace existing drafts on regenerate
            </label>
          </div>
        )}
      </div>

      <div className="mt-4">
        <h3 className="text-sm font-semibold text-slate-900">Tailored resume (draft)</h3>
        {data.materials.tailoredResume ? (
          <div className="mt-1 rounded-md bg-slate-50 px-3 py-2 text-sm">
            <p className="text-slate-700">{data.materials.tailoredResume.summary}</p>
            {data.materials.tailoredResume.highlights.length > 0 && (
              <ul className="mt-1 list-disc pl-5 text-slate-700">
                {data.materials.tailoredResume.highlights.map((h) => (
                  <li key={h}>{h}</li>
                ))}
              </ul>
            )}
            {data.materials.tailoredResume.skillsUsed.length > 0 && (
              <p className="mt-1 text-slate-600">
                Verified skills used: {data.materials.tailoredResume.skillsUsed.join(', ')}
              </p>
            )}
            {data.materials.tailoredResume.flaggedGaps.length > 0 && (
              <div className="mt-2 rounded-md border border-amber-300 bg-amber-50 px-3 py-2 text-amber-800">
                <p className="font-semibold">Missing information</p>
                <ul className="list-disc pl-5">
                  {data.materials.tailoredResume.flaggedGaps.map((gap) => (
                    <li key={gap}>{gap}</li>
                  ))}
                </ul>
              </div>
            )}
            <p className="mt-1 text-xs text-slate-500">The original resume file is unchanged.</p>
          </div>
        ) : (
          <p className="mt-1 text-sm text-slate-600">No tailored resume draft yet.</p>
        )}
        {editable && (
          <button
            type="button"
            disabled={busy !== null}
            onClick={() =>
              void run('resume generation', async () => {
                await generateResumeDraft(applicationId, replace)
                setNotice('Tailored resume draft generated. Review every line before use.')
              })
            }
            className="mt-2 rounded-md bg-slate-900 px-3 py-1.5 text-sm font-medium text-white disabled:opacity-50"
          >
            {busy === 'resume generation'
              ? 'Generating…'
              : data.materials.tailoredResume
                ? 'Regenerate resume'
                : 'Generate resume'}
          </button>
        )}
      </div>

      <div className="mt-4">
        <h3 className="text-sm font-semibold text-slate-900">Question answers (drafts)</h3>
        {editable && (
          <div className="mt-1 flex flex-wrap gap-2">
            <input
              aria-label="Application question"
              placeholder="e.g. Why do you want this role?"
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              className="min-w-0 flex-1 rounded-md border border-slate-300 px-2 py-1.5 text-sm"
            />
            <button
              type="button"
              disabled={busy !== null || !question.trim()}
              onClick={() =>
                void run('answer generation', async () => {
                  await generateAnswer(applicationId, question.trim(), replace)
                  setQuestion('')
                  setNotice('Answer draft generated as unverified — confirm before submitting.')
                })
              }
              className="rounded-md bg-slate-900 px-3 py-1.5 text-sm font-medium text-white disabled:opacity-50"
            >
              {busy === 'answer generation' ? 'Generating…' : 'Generate answer'}
            </button>
          </div>
        )}
        {answers.length === 0 && <p className="mt-1 text-sm text-slate-600">No answers recorded yet.</p>}
        <ul className="mt-2 space-y-2">
          {answers.map((answer, index) => (
            <li key={answer.question} className="rounded-md bg-slate-50 px-3 py-2 text-sm">
              <p className="font-medium text-slate-900">{answer.question}</p>
              <textarea
                aria-label={`Answer to ${answer.question}`}
                value={answer.answer}
                disabled={!editable}
                onChange={(e) =>
                  setAnswers((prev) => prev.map((a, i) => (i === index ? { ...a, answer: e.target.value } : a)))
                }
                rows={3}
                className="mt-1 block w-full rounded-md border border-slate-300 px-2 py-1.5 disabled:bg-slate-100"
              />
              <label className="mt-1 flex items-center gap-1 text-xs text-slate-600">
                <input
                  type="checkbox"
                  checked={answer.verified}
                  disabled={!editable}
                  onChange={(e) =>
                    setAnswers((prev) => prev.map((a, i) => (i === index ? { ...a, verified: e.target.checked } : a)))
                  }
                />
                Verified by me{answer.sensitive ? ' · sensitive declaration' : ''}
                {!answer.verified ? ' · unverified — needs confirmation' : ''}
              </label>
            </li>
          ))}
        </ul>
        {editable && answers.length > 0 && (
          <button
            type="button"
            disabled={busy !== null}
            onClick={() =>
              void run('answers save', async () => {
                await updateApplicationMaterials(applicationId, { answers })
                setNotice('Answers saved.')
              })
            }
            className="mt-2 rounded-md border border-slate-300 px-3 py-1.5 text-sm font-medium text-slate-700 disabled:opacity-50"
          >
            Save answers
          </button>
        )}
      </div>

      {reviewable && (
        <button
          type="button"
          disabled={busy !== null}
          onClick={() =>
            void run('materials review', async () => {
              await markMaterialsReviewed(applicationId)
              setNotice('Materials marked as reviewed.')
            })
          }
          className="mt-4 rounded-md bg-emerald-700 px-3 py-1.5 text-sm font-medium text-white disabled:opacity-50"
        >
          Mark materials as reviewed
        </button>
      )}
    </div>
  )
}
